# 主题：DataFrame 创建 / 侦察（shape、describe）/ 选列 / 条件筛选

import pandas as pd

df = pd.DataFrame({
    '姓名': ['小明', '小红', '小刚', '小美', '大壮'],
    '数学': [85, 92, 78, 95, 60],
    '英语': [70, 88, 95, 82, 65]
})

# ── 1. 形状 ──────────────────────────────
# 预测：df.shape = (5, 3)
print(df.shape)

# ── 2. 侦察函数 ──────────────────────────
# 预测：输出类似 ['小明', 85, 70] 这样的每行内容
print(df.info())
print(df.describe())

# ── 3. 选列 ──────────────────────────────
# 预测：不确定（Series 还是 DataFrame）
print(df['数学'])

# ── 4. 条件筛选 ──────────────────────────
# 预测：不确定（几个人）
print(df[df['数学'] >= 85])
