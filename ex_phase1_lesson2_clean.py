# 主题：isnull / duplicated / dropna / fillna；NaN 致 int 升 float64
import numpy as np
import pandas as pd

df = pd.DataFrame({
    '姓名': ['小明', '小红', '小刚', '小美', '大壮', '小明'],
    '数学': [85, 92, np.nan, 95, 60, 85],
    '英语': [70, np.nan, 95, 82, 65, 70],
})

# ── 任务 1：探测缺失 ──────────────────────
# 预测：数学、英语各缺几个？：各缺1个
print(df.isnull().sum())

# ── 任务 2：探测重复 ──────────────────────
# 预测：duplicated() 会标出第几行是 True？第6行，序号为5
print(df.duplicated())

# ── 任务 3：删除缺失行 ────────────────────
# 预测：dropna() 之后还剩几行？4行
print(df.dropna())

# ── 任务 4：清洗流水线 ────────────────────
# 先去重，再用各自平均分填缺失
# 预测：小刚的数学会被填成多少？小红的英语会被填成多少？（提示：先想清楚去重后均值怎么算）去重后省下5行，但包含一个np.nan就只剩下4个元素，4个元素求和得均值83 78，最后的平均值类型变了带.0没有进行数据转换就填充了，除非该Series强制为int
df = df.drop_duplicates()
df['数学'] = df['数学'].fillna(df['数学'].mean())
df['英语'] = df['英语'].fillna(df['英语'].mean())
print(df)
